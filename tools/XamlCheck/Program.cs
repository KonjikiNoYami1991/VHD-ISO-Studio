// XamlCheck: verifica statica dei file XAML contro gli assembly di riferimento WPF.
//  - ogni elemento corrisponde a un tipo WPF (o del namespace l:)
//  - ogni attributo e' una proprieta'/evento del tipo, oppure una proprieta'/evento associato (Owner.Prop)
//  - Setter/Trigger Property esistono sul TargetType
//  - genera Stubs.g.cs: campi x:Name tipizzati, InitializeComponent vuoto, e codice che aggancia
//    ogni gestore di evento (cosi' il compilatore C# ne verifica esistenza e firma) e ogni {x:Static}.
// Uso: XamlCheck <cartella-ref-wpf> <cartella-progetto> <file-stub-output>
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;

var refDir = args[0];
var projDir = args[1];
var stubOut = args[2];
var paths = Directory.GetFiles(refDir, "*.dll").ToList();
// assembly di base: quelli del runtime che esegue lo strumento (System.Runtime, ecc.)
var coreDir = System.Runtime.InteropServices.RuntimeEnvironment.GetRuntimeDirectory();
paths.AddRange(Directory.GetFiles(coreDir, "*.dll").Where(p => !paths.Any(x => Path.GetFileName(x) == Path.GetFileName(p))));
var resolver = new PathAssemblyResolver(paths.GroupBy(Path.GetFileName).Select(g => g.First()));
using var mlc = new MetadataLoadContext(resolver, "System.Runtime");
var wpfAsm = new[] { "PresentationFramework", "PresentationCore", "WindowsBase", "System.Xaml" }
    .Select(n => mlc.LoadFromAssemblyPath(Path.Combine(refDir, n + ".dll"))).ToList();
var wpfTypes = wpfAsm.SelectMany(a => a.GetExportedTypes())
    .Where(t => t.Namespace != null && (t.Namespace.StartsWith("System.Windows") || t.Namespace == "System.Windows"))
    .GroupBy(t => t.Name).ToDictionary(g => g.Key, g => g.OrderBy(t => t.Namespace!.Length).First());

const string WpfNs = "http://schemas.microsoft.com/winfx/2006/xaml/presentation";
const string XNs = "http://schemas.microsoft.com/winfx/2006/xaml";
int errors = 0;
void Err(string file, XObject o, string msg)
{
    var li = (System.Xml.IXmlLineInfo)o;
    Console.WriteLine($"{Path.GetFileName(file)}({li.LineNumber}): {msg}");
    errors++;
}

Type? Resolve(string name) => wpfTypes.TryGetValue(name, out var t) ? t : null;

IEnumerable<Type> Chain(Type t) { for (var c = t; c != null; c = c.BaseType) yield return c; }

bool HasMember(Type t, string name) =>
    Chain(t).Any(c => c.GetProperty(name, BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly) != null
                   || c.GetEvent(name, BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly) != null);

bool HasAttached(Type owner, string name) =>
    Chain(owner).Any(c => c.GetField(name + "Property", BindingFlags.Public | BindingFlags.Static) != null
                       || c.GetField(name + "Event", BindingFlags.Public | BindingFlags.Static) != null
                       || c.GetMethod("Set" + name, BindingFlags.Public | BindingFlags.Static) != null)
    || HasMember(owner, name);

Type? ParseTypeRef(string v)
{
    var m = Regex.Match(v, @"^\{x:Type\s+(\w+)\}$");
    return Resolve(m.Success ? m.Groups[1].Value : v);
}

var stub = new StringBuilder();
stub.AppendLine("// <auto-generated> da tools/XamlCheck: SOLO per la verifica di compilazione su Linux </auto-generated>");
stub.AppendLine("#pragma warning disable CS0169, CS0649, CS8618, CS0414, CS8602");
int dummy = 0;

foreach (var file in Directory.GetFiles(projDir, "*.xaml", SearchOption.AllDirectories).Where(f => !f.Contains("/obj/") && !f.Contains("/bin/")))
{
    var doc = XDocument.Load(file, LoadOptions.SetLineInfo);
    var root = doc.Root!;
    string? cls = root.Attribute(XName.Get("Class", XNs))?.Value;
    var fields = new List<string>();
    var hooks = new List<string>();

    foreach (var el in root.DescendantsAndSelf())
    {
        string local = el.Name.LocalName;
        string ns = el.Name.NamespaceName;
        Type? type = null;
        if (ns == WpfNs)
        {
            if (local.Contains('.'))
            {
                // property element: Owner.Prop
                var parts = local.Split('.');
                var owner = Resolve(parts[0]);
                if (owner == null) Err(file, el, $"tipo sconosciuto '{parts[0]}' in property element");
                else if (!HasAttached(owner, parts[1])) Err(file, el, $"'{parts[1]}' non esiste su {owner.Name}");
                continue;
            }
            type = Resolve(local);
            if (type == null) { Err(file, el, $"tipo WPF sconosciuto '{local}'"); continue; }
        }
        else if (ns == XNs) continue;
        else continue; // namespace locali (l:) verificati dal compilatore tramite gli stub

        string? name = el.Attribute(XName.Get("Name", XNs))?.Value ?? el.Attribute("Name")?.Value;
        if (name != null && cls != null && el != root) fields.Add($"    internal {type.FullName} {name};");
        string target = el == root ? "this" : name ?? $"__d{++dummy}";
        bool needsDummy = el != root && name == null;

        foreach (var at in el.Attributes())
        {
            if (at.IsNamespaceDeclaration || at.Name.NamespaceName == XNs) continue;
            if (at.Name.NamespaceName != "") { Err(file, at, $"attributo con namespace inatteso {at.Name}"); continue; }
            string an = at.Name.LocalName;
            string val = at.Value;

            // {x:Static l:Enum.Value}
            foreach (Match m in Regex.Matches(val, @"\{x:Static l:([\w\.]+)\}"))
                hooks.Add($"        _ = VhdIsoStudio.Core.{m.Groups[1].Value};");

            if (an.Contains('.'))
            {
                var parts = an.Split('.');
                var owner = Resolve(parts[0]);
                if (owner == null) Err(file, at, $"owner sconosciuto '{parts[0]}'");
                else if (!HasAttached(owner, parts[1])) Err(file, at, $"proprieta' associata '{an}' inesistente");
                continue;
            }
            if (!HasMember(type, an)) { Err(file, at, $"'{an}' non e' proprieta'/evento di {type.Name}"); continue; }

            // evento con gestore -> aggancio nello stub
            var ev = Chain(type).Select(c => c.GetEvent(an, BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)).FirstOrDefault(e => e != null);
            if (ev != null && cls != null && !val.StartsWith("{"))
            {
                if (needsDummy) hooks.Add($"        {{ var {target} = new {type.FullName}(); {target}.{an} += {val}; }}");
                else hooks.Add($"        {target}.{an} += {val};");
            }

            // Setter / Trigger: Property sul TargetType
            if ((local is "Setter" or "Trigger" or "Condition") && an == "Property" && el.Attribute("TargetName") == null)
            {
                Type? tt = null;
                for (var p = el.Parent; p != null && tt == null; p = p.Parent)
                {
                    var ta = p.Attribute("TargetType");
                    if (ta != null) tt = ParseTypeRef(ta.Value);
                }
                if (val.Contains('.'))
                {
                    var parts = val.Split('.');
                    var owner = Resolve(parts[0]);
                    if (owner == null || !HasAttached(owner, parts[1])) Err(file, at, $"Property '{val}' inesistente");
                }
                else if (tt != null && !HasMember(tt, val)) Err(file, at, $"Property '{val}' inesistente su {tt.Name}");
            }
            if (an == "TargetType" && ParseTypeRef(val) == null) Err(file, at, $"TargetType sconosciuto '{val}'");
        }
    }

    if (cls != null)
    {
        int dot = cls.LastIndexOf('.');
        string nsName = cls[..dot], clsName = cls[(dot + 1)..];
        var rootType = Resolve(root.Name.LocalName)!;
        stub.AppendLine($"namespace {nsName} {{");
        stub.AppendLine($"public partial class {clsName} : {rootType.FullName} {{");
        fields.ForEach(f => stub.AppendLine(f));
        stub.AppendLine("    public void InitializeComponent() { }");
        stub.AppendLine("    private void __XamlCheckHooks() {");
        hooks.ForEach(h => stub.AppendLine(h));
        stub.AppendLine("    }");
        stub.AppendLine("}}");
    }
}

File.WriteAllText(stubOut, stub.ToString());
Console.WriteLine(errors == 0 ? "XamlCheck: OK" : $"XamlCheck: {errors} errori");
return errors == 0 ? 0 : 1;
